import { test, expect } from '@playwright/test';

test('keyboard, focus, state styles, render props, and portal theme', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('console', (message) => { if (message.type() === 'error') errors.push(`${message.text()} ${message.location().url}`); });
  await page.goto('/');
  const trigger = page.getByRole('button', { name: 'Open settings', includeHidden: true });
  await page.keyboard.press('Tab');
  await expect(trigger).toBeFocused();
  await expect(trigger).toHaveCSS('outline-width', '3px');
  await expect(trigger).toHaveCSS('border-bottom-width', '2px');
  await page.keyboard.press('Enter');
  const dialog = page.getByRole('dialog', { name: 'Settings' });
  const theme = dialog.getByRole('button', { name: 'Switch to dark theme' });
  const close = dialog.getByRole('button', { name: 'Close settings' });
  await expect(dialog).toBeVisible();
  await expect(page.getByRole('button', { name: 'Open settings' })).toHaveCount(0);
  await expect(dialog).toHaveAccessibleDescription('Choose the page appearance.');
  await expect(theme).toBeFocused();
  await expect(theme).toHaveCSS('outline-width', '3px');
  await expect(trigger).toHaveCSS('border-bottom-width', '6px');
  await expect(dialog).toHaveCSS('border-width', '3px');
  expect(await dialog.evaluate((node) => node.closest('main'))).toBeNull();
  await expect(dialog).toHaveCSS('background-color', 'rgb(255, 255, 255)');
  // Exercise backwards and forwards trapping, including both ends of the loop.
  await page.keyboard.press('Shift+Tab');
  await expect(close).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(theme).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(close).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(theme).toBeFocused();
  await page.keyboard.press('Space');
  await expect(dialog).toHaveCSS('background-color', 'rgb(23, 33, 43)');
  await expect(page.locator('main')).toHaveCSS('background-color', 'rgb(23, 33, 43)');
  await expect(dialog).toHaveCSS('color', 'rgb(255, 255, 255)');
  const rect = await dialog.boundingBox();
  expect(rect).not.toBeNull();
  expect(rect!.x).toBeGreaterThanOrEqual(0);
  expect(rect!.x + rect!.width).toBeLessThanOrEqual(page.viewportSize()!.width);
  await page.screenshot({ path: testInfo.outputPath('dark-dialog.png'), fullPage: true });
  await page.keyboard.press('Escape');
  await expect(dialog).toBeHidden();
  await expect(trigger).toBeFocused();
  await expect(trigger).toHaveCSS('border-bottom-width', '2px');
  await page.keyboard.press('Space');
  await expect(dialog).toBeVisible();
  await expect(dialog).toHaveCSS('background-color', 'rgb(23, 33, 43)');
  await page.keyboard.press('Tab');
  await expect(close).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(dialog).toBeHidden();
  await expect(trigger).toBeFocused();
  await expect(page.getByLabel('Close clicks')).toHaveText('1');
  await trigger.click();
  await expect(dialog).toBeVisible();
  await page.mouse.click(4, 4);
  await expect(dialog).toBeHidden();
  await expect(trigger).toBeFocused();
  expect(errors).toEqual([]);
});
